    private void cashItems(boolean spanish) {
        for (Denomination denomination : Denomination.values()) {
            add("item." + UMA.MODID + "." + denomination.itemName(), cashName(denomination, spanish));
        }
    }

    private static String cashName(Denomination denomination, boolean spanish) {
        long mangos = denomination.cents() / Denomination.CENTS_PER_MANGO;
        if (denomination.cents() < Denomination.CENTS_PER_MANGO) {
            return denomination.cents() + (spanish ? " centavos" : " Centavos");
        }
        if (denomination.kind() == Denomination.Kind.COIN) {
            return mangos + (spanish ? " pesos" : " Pesos");
        }
        long lucas = mangos / 1000L;
        if (lucas > 0L) {
            String unit = lucas == 1L ? (spanish ? "luca" : "Luca") : (spanish ? "lucas" : "Lucas");
            return (spanish ? "Billete de " : "") + lucas + " " + unit + (spanish ? "" : " Bill");
        }
        return (spanish ? "Billete de " : "") + mangos + (spanish ? " mangos" : " Mango Bill");
    }

